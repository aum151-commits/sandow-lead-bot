    # QUIET_TO, 22:00–10:00).
    when = "в течение часа" if not is_quiet() else "в ближайшие рабочие часы"

    # АВТОПОДБОР (16.10.2026). До отправки карточки выясняем, может ли бот
    # поставить тренера сам. Если да — клиент получает не «сверю время», а
