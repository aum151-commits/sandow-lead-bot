# ── Автоподбор тренера: задача, здоровье, пожелание по полу, очередь ────────
#
# Правило Ольги 16.10.2026: запись на тренировку распределяется автоматически,
# а не через координатора. Координатор при этом узнаёт о каждой записи — но не
# решает, а видит: кто к кому попал и где возникло провисание.
#
# Выбор идёт в три шага, и порядок шагов — это и есть содержание решения:
#
#   1) ЖЁСТКИЙ ФИЛЬТР по задаче. Направление (бокс) и особенности здоровья
#      (осанка, опорно-двигательный аппарат) — не «пожелание», а условие:
#      тренер без нужной компетенции в список не попадает вообще. Клиент с
#      грыжей не должен получить тренера, который с этим не работает.
#   2) ПОЖЕЛАНИЕ ПО ПОЛУ — второй фильтр, и он мягкий. Если подходящих
#      нужного пола нет, бот не решает за клиента и не подсовывает молча
#      человека без нужной компетенции: он спрашивает (решение Ольги
#      16.10.2026, основание — слова координатора: «для некоторых клиентов
#      пол принципиален, но это единицы»).
#   3) ОЧЕРЕДЬ. Среди тех, кто прошёл первые два шага и свободен в это время,
#      берётся первый по алфавитной очереди, после чего уходит в конец. Так
#      ход доходит до всех, и доступ к клиентам равный.
#
# ЧЕГО Я НЕ СТАЛА ДЕЛАТЬ, ХОТЯ ПРЕДЛАГАЛА САМА. Была идея выбирать «кто точнее
# совпал», взвешивая компетенции по редкости: осанка весит много, «набор
# массы» — почти ничего. Проверка на живых данных показала, что это ломает
# ровно ту справедливость, ради которой очередь и заведена: базовый набор
# (набор массы, коррекция фигуры, функциональные тренировки, сопровождение по
# питанию) есть у 17 из 18 тренеров, поэтому вес по редкости вытаскивал наверх
# одних и тех же — кроссфит-тренеров. Редкие компетенции работают жёстким
# фильтром (шаг 1), а порядок определяет очередь.
#
# Файлы данных лежат отдельно от кода: компетенции меняются (тренер прошёл
# курс, вернулся, ушёл), и выкладывать бота из-за каждой строчки не нужно.
PROFILES_PATH = "data/trainers/profiles.json"
QUEUE_PATH = "data/trainers/queue.json"
# Сколько ждём ответа тренера на карточку гостя, прежде чем передать запись
# следующему. 30 минут — решение Ольги 16.10.2026.
TRAINER_ANSWER_MIN = 30
_PROFILES = {"когда": 0.0, "данные": None}
_QUEUE = {"когда": 0.0, "порядок": None}
# Пол в профиле — одна буква, а клиенту и координатору нужно слово.
ПОЛ_СЛОВО = {"ж": "женщина-тренер", "м": "мужчина-тренер"}
# Почему автоподбор не смог — текстом для карточки. Координатор должна видеть
# причину, а не код: «нет_окон» ей ничего не объясняет, а «окна на это время
# никто не отметил» — объясняет и подсказывает, что делать.
ПРИЧИНЫ_ОТКАЗА = {
    "нет_компетенций": "под задачу не подходит ни один тренер по компетенциям",
    "нужен_другой_пол": "подходят только тренеры другого пола — спросили клиента",
    "нет_окон": "на это время окна никто не отметил",
    "": "",
}


def фамилия(имя):
    """Фамилия для алфавитного порядка. Имена у нас записаны как «Имя
    Фамилия», а очередь Ольга задала «по первой букве фамилии»."""
    части = (имя or "").split()
    return части[-1] if части else ""


def _настройка_подбора():
    """Файл профилей целиком: правила (цели, направления, здоровье) и люди.
    Кэш на 10 минут — подбор случается чаще, чем меняется файл."""
    if _PROFILES["данные"] is not None and time.time() - _PROFILES["когда"] < 600:
        return _PROFILES["данные"]
    данные = gh_read_json(PROFILES_PATH, default={}) or {}
    if not данные.get("тренеры"):
        print("[подбор] профили тренеров не прочитались — автоподбор выключен",
              flush=True)
    _PROFILES["данные"], _PROFILES["когда"] = данные, time.time()
    return данные


def профили():
    """Имя → профиль тренера. Ушедшие из клуба не попадают."""
    данные = _настройка_подбора()
    return {т.get("имя"): т for т in (данные.get("тренеры") or [])
            if работает_в_клубе(т.get("имя"))}


def нужное_по_здоровью(health):
    """Что человек написал о здоровье → какие компетенции обязательны.

    Слова ищем по корням, а не целиком: «грыжа», «грыжи», «с грыжей» — один
    признак, а живой текст пишут как хотят. Возвращаем и названия признаков:
    они идут в отчёт координатору, чтобы было видно, по какому поводу подобран
    тренер.
    """
    текст = (health or "").lower()
    нужно, признаки = [], []
    for пункт in (_настройка_подбора().get("здоровье") or []):
        if any(слово in текст for слово in (пункт.get("слова") or [])):
            признаки.append(пункт.get("признак", ""))
            нужно += пункт.get("компетенции") or []
    return list(dict.fromkeys(нужно)), [п for п in признаки if п]


def очередь():
    """Алфавитная очередь тренеров: первый в списке — чей сейчас ход.

    Устроена как поворот алфавитного списка, а не как счётчик: получивший
    клиента встаёт в конец, и порядок остаётся алфавитным по кругу — ровно то,
    что описала Ольга. Тренер, пропущенный из-за окон, места не теряет: его
    никто не двигает, двигается только тот, кому запись реально досталась.

    Новый тренер доставляется в конец списка, а не вставляется по алфавиту:
    вставка в середину сдвинула бы ход у всех, кто уже стоит за ним.
    """
    if _QUEUE["порядок"] and time.time() - _QUEUE["когда"] < 300:
        return list(_QUEUE["порядок"])
    данные = gh_read_json(QUEUE_PATH, default={}) or {}
    действующие = [и for и in _TRAINERS if работает_в_клубе(и)]
    порядок = [и for и in (данные.get("порядок") or []) if и in действующие]
    порядок += [и for и in действующие if и not in порядок]
    if not данные.get("порядок"):
        # Первый запуск: очередь собирается по алфавиту фамилий.
        порядок = sorted(порядок, key=lambda и: (фамилия(и).lower(), и.lower()))

        def _собрать(d, п=порядок):
            d["порядок"] = п
            d["обновлено"] = datetime.now(MSK).strftime("%Y-%m-%d %H:%M")
        gh_update_json(QUEUE_PATH, _собрать, "очередь тренеров: собрана по алфавиту")
        print(f"[подбор] очередь собрана: {', '.join(порядок)}", flush=True)
    elif порядок != (данные.get("порядок") or []):
        def _доставить(d, п=порядок):
            d["порядок"] = п
        gh_update_json(QUEUE_PATH, _доставить, "очередь тренеров: состав обновлён")
    _QUEUE["порядок"], _QUEUE["когда"] = порядок, time.time()
    return list(порядок)


def _ход_отдан(имя):
    """Тренер получил клиента — его ход уходит в конец очереди."""
    def _сдвиг(d, и=имя):
        d["порядок"] = [x for x in (d.get("порядок") or []) if x != и] + [и]
        d["обновлено"] = datetime.now(MSK).strftime("%Y-%m-%d %H:%M")
    gh_update_json(QUEUE_PATH, _сдвиг, f"очередь тренеров: {имя} — ход отдан")
    _QUEUE["порядок"] = None            # кэш сбрасываем, следующий ход возьмёт свежий


def разбор_подбора(goal, direction, health, кроме=()):
    """Кто вообще подходит под задачу — без учёта времени и пола.

    Отделено от выбора специально: этот список нужен и в отчёте координатору
    («под задачу подходили: …»), и при подборе по полу. `кроме` — тренеры,
    которых рассматривать нельзя: при передаче записи следующему прежний
    тренер не должен выпасть сам себе.
    """
    правила = _настройка_подбора()
    нужно_здоровье, признаки = нужное_по_здоровью(health)
    по_направлению = (правила.get("направления") or {}).get(direction or "any") or []
    по_цели = (правила.get("цели") or {}).get(goal or "keep") or []
    карта = профили()
    # Сначала жёсткие условия — направление и здоровье. Цель применяется
    # вторым проходом, и только если направления у клиента нет вовсе: когда
    # человек выбрал бокс, его задача — бокс, а не «набрать форму и силу»
    # вообще. Без этого правила эксперт по боксу Виктор Савельев выпадал из
    # подбора у клиента, чья цель звучит как «набрать форму и силу»: в его
    # компетенциях только бокс, и по цели он не проходит. Это был бы отказ
    # клиенту в лучшем тренере под его выбор — из-за анкеты, а не из-за дела.
    жёстко = []
    for имя in очередь():
        if имя in кроме:
            continue
        п = карта.get(имя)
        if not п:
            continue
        ком = set(п.get("компетенции") or [])
        if по_направлению and not (ком & set(по_направлению)):
            continue
        if нужно_здоровье and not set(нужно_здоровье) <= ком:
            continue
        жёстко.append(имя)
    if по_направлению or not по_цели:
        годные = жёстко
    else:
        годные = [и for и in жёстко
                  if set((карта.get(и) or {}).get("компетенции") or []) & set(по_цели)]
        if not годные:                 # цель не должна оставлять пустой список
            годные = жёстко
    return годные, {"здоровье": нужно_здоровье, "признаки": признаки,
                    "направление": по_направлению, "цель": по_цели}


def авто_тренер(goal, direction, health, visit_date=None, visit_slot=None,
                пол="any", кроме=()):
    """Кого поставить на запись. Возвращает разбор, а не только имя: причина
    отказа идёт в отчёт координатору, иначе провисание нельзя объяснить.

    Причины: "" — нашли; «нет_компетенций» — под задачу не подходит никто;
    «нужен_другой_пол» — подходящие есть, но другого пола (тут бот спрашивает
    клиента, а не решает сам); «нет_окон» — подходящие есть, но на это время
    никто не открыл окна.
    """
    годные, разбор = разбор_подбора(goal, direction, health, кроме)
    итог = {"тренер": None, "причина": "", "альтернативы": [], "разбор": разбор,
            "годные": годные}
    if not годные:
        итог["причина"] = "нет_компетенций"
        return итог
    карта = профили()
    if пол in ("ж", "м"):
        своего_пола = [и for и in годные if (карта.get(и) or {}).get("пол") == пол]
    else:
        своего_пола = годные
    if not своего_пола:
        другой = "м" if пол == "ж" else "ж"
        итог["альтернативы"] = [и for и in годные
                                if (карта.get(и) or {}).get("пол") == другой]
        итог["причина"] = "нужен_другой_пол"
        return итог
    свободные = _free_trainers_for(visit_date, visit_slot)
    for имя in своего_пола:
        if имя in свободные:
            итог["тренер"] = имя
            return итог
    итог["причина"] = "нет_окон"
    return итог


