    gh_update_json(BOOKINGS_PATH, _отметить,
                   f"тг-бот: клиент {'подтвердил' if подтвердил else 'просит перенести'} {когда}")

    # Текст ответа — правка Ольги 13.10.2026, дословно: «Спасибо, Иван! Ждём вас
    # завтра — если будут вопросы — пишите здесь, поможем (смайлик)».
