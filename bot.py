def _тренер_молчит(з, now):
    """Тренер получил карточку гостя и не ответил за отведённое время.

    Точка отсчёта — момент назначения, а не создания записи: при ручном
    выборе координатором тренер появляется позже, и отсчитывать надо от него.
    """
    метка = з.get("trainer_assigned") or з.get("created") or ""
    try:
        назначено = datetime.strptime(метка, "%Y-%m-%d %H:%M").replace(tzinfo=MSK)
    except (TypeError, ValueError):
        return False
    return now - назначено >= timedelta(minutes=TRAINER_ANSWER_MIN)


