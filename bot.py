def _self_ping():
    """Держит бесплатный сервис Render в тонусе — сам стучится на свой
    публичный адрес каждые ~10 минут, тем же приёмом, что уже работает
    у sandow-cron (память cloud-scheduler-own-heartbeat, 02.09.2026).
    Не зависит ни от ноутбука, ни от расписания GitHub Actions (оно
    достоверно опаздывает на часы вместо минут — известное свойство
    платформы, не наша поломка). Правка Ольги 28.09.2026: бот теперь
    на отдельном Render-аккаунте только для себя, поэтому круглосуточный
    self-ping не делит лимит часов ни с кем ещё."""
    url = os.environ.get("RENDER_EXTERNAL_URL", "").rstrip("/")
    if not url:
        print("[self-ping] RENDER_EXTERNAL_URL не задан — самопробуждение выключено", flush=True)
        return
    while True:
        try:
            requests.get(f"{url}/health", timeout=30)
        except Exception as exc:
            print(f"[self-ping] {exc}", flush=True)
        time.sleep(600)


def _убрать_ушедших():
    """Разовая уборка файлов данных от тренеров, которых больше нет в клубе.

    Зачем отдельно от фильтра в коде: в `trainer_subscribers.json` ушедший
    тренер — это его chat_id, и по нему ему каждый вечер уходили окна и
    напоминания, а его имя стояло в сводке координатору. Фильтр прячет это
    от глаз, но запись остаётся живой. Здесь она удаляется по-настоящему.

    Пишем через `gh_update_json`: он ведёт и российский бакет, и копию в
    репозитории — руками отсюда до бакета не дотянуться (ключей в проекте
    нет). Уборка идемпотентна: нет ушедших — нет и записи.
    """
    try:
        состав = gh_read_json(TRAINER_GH_PATH, default={}) or {}
        есть_в_составе = [k for k, r in состав.items()
                          if not работает_в_клубе((r or {}).get("name"))]
        if есть_в_составе:
            имена = [состав[k].get("name") for k in есть_в_составе]

            def _из_состава(d):
                for k in list(d):
                    if not работает_в_клубе((d.get(k) or {}).get("name")):
                        d.pop(k, None)

            gh_update_json(TRAINER_GH_PATH, _из_состава,
                           f"тренеры: убраны ушедшие из клуба ({', '.join(имена)})")
            print(f"[состав] убраны ушедшие: {', '.join(имена)}", flush=True)

        окна = gh_read_json(TRAINER_SLOTS_PATH, default={}) or {}
        найдено = {n for день in (окна.get("days") or {}).values()
                   for n in (день or {}) if not работает_в_клубе(n)}
        if найдено:
            def _из_окон(d):
                for день in ((d or {}).get("days") or {}).values():
                    for имя in [n for n in (день or {}) if not работает_в_клубе(n)]:
                        день.pop(имя, None)

            gh_update_json(TRAINER_SLOTS_PATH, _из_окон,
                           f"окна: убраны ушедшие из клуба ({', '.join(sorted(найдено))})")
            print(f"[состав] окна ушедших убраны: {', '.join(sorted(найдено))}", flush=True)

        # Третье место — список состава, по которому разбираются отметки в чате
        # продаж. Его ведёт облачная сверка `sync_staff.py`, и она устроена
        # намеренно осторожно: имя, пропавшее с сайта, она показывает в письме,
        # но из списка НЕ убирает (переверстали блок — и половина состава
        # исчезла бы молча). Из-за этого ушедший тренер оставался в списке
        # навсегда и каждую неделю попадал в письмо как «пропал с сайта».
        # Здесь убираем его поимённо: для ушедших осторожность не нужна.
        состав_отметок = gh_read_json(STAFF_PATH, default={}) or {}
        лишние = [t for t in (состав_отметок.get("тренеры") or [])
                  if not работает_в_клубе(t)]
        if лишние:
            def _из_состава_отметок(d):
                d["тренеры"] = [t for t in (d.get("тренеры") or [])
                                if работает_в_клубе(t)]

            gh_update_json(STAFF_PATH, _из_состава_отметок,
                           f"состав: убраны ушедшие из клуба ({', '.join(лишние)})")
            print(f"[состав] из списка отметок убраны: {', '.join(лишние)}", flush=True)
    except Exception as exc:                      # уборка не должна ронять старт
        print(f"[состав] уборка ушедших: {exc}", flush=True)


