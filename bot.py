        предложен = (подбор.get("альтернативы") or [None])[0]
        with LOCK:
            STATE.setdefault(chat_id, {})["sex_offer"] = предложен
        отчёт_о_провисании(
            chat_id, итог_для_отчёта(chat_id, name, phone, time_pref, подбор,
                                     st.get("goal", "keep")),
            f"Под задачу подходят только тренеры другого пола; "
            f"клиенту предложен {предложен or '—'}, ждём ответа.")
        api("sendMessage", chat_id=chat_id, parse_mode="HTML",
            text=(f"Под вашу задачу на {time_pref} подходит фитнес-эксперт "
                  f"<b>{предложен}</b>. Подскажите, пожалуйста, он вам подходит?"),
            reply_markup=kb([[("Да, подходит", "tsexok:да")],
                             [("Нужен другой тренер", "tsexok:нет")]]))


