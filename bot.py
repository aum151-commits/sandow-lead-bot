def step_slots(chat_id, message_id, iso, fmt):
    """Часы выбранного дня. iso — дата из кнопки дня; пришло что-то другое
    (старое сообщение с днём недели, мусор) — показываем выбор дня заново."""
    if iso not in horizon_dates():
        return step_time(chat_id, fmt, message_id=message_id)
    slots = slots_on(iso, fmt, chat_id)
    if not slots:
        return step_time(chat_id, fmt, message_id=message_id,
                         text="На сегодня свободных часов уже не осталось — "
                              "выберите другой день:")
    rows = [[(t, f"sl:{fmt}:{iso}:{t}")] for t in slots]
    # Кнопки «Своё время» здесь больше нет — правка Ольги 16.10.2026, дословно:
    # «и на 15.30 не было времени. наверное не стоит тогда предлагать своё время
    # клиенту?» Она права по сути: клуб и тренеры работают целыми часами
    # (SLOT_LIST — с шагом в час), поэтому «15:30» из свободного ввода всё равно
    # не подтверждается. Предлагать время, которого у клуба нет, — это обещание,
    # которое тут же ломается, а человек уже настроился.
    #
    # Обработка чужого времени оставлена: у части клиентов в чате висит старое
    # сообщение с этой кнопкой, и нажатие по нему не должно приводить к молчанию.
    api("editMessageText", chat_id=chat_id, message_id=message_id,
        text=f"Выберите время — {fmt_date_long(iso)}:", reply_markup=kb(rows))


