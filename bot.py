    # Запоминаем запись ДО подтверждения: coordinator_confirm дописывает в неё
    # тренера и без записи ему нечего дописывать.
    remember_booking(chat_id, user, {**st, "phone": phone, "goal": st.get("goal", "keep"),
                                     "trainer_name": тренер or ""})

    if тренер:
        итог = итог_для_отчёта(chat_id, name, phone, time_pref, подбор,
                               st.get("goal", "keep"))
