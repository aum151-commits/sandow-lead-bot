def отчёт_координатору(chat_id, тренер, разбор, пол=""):
    """Кто к кому попал — человеческой строкой, без внутренних кодов."""
    имя = разбор.get("имя") or "без имени"
    телефон = f" · <code>{разбор.get('телефон')}</code>" if разбор.get("телефон") else ""
    повод = []
    if разбор.get("признаки"):
        повод.append("здоровье: " + ", ".join(разбор["признаки"]))
    if разбор.get("цель_слово"):
        повод.append(разбор["цель_слово"])
    if пол:
        повод.append(ПОЛ_СЛОВО.get(пол, пол))
