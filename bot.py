def visit_tick(now=None):
    """Напоминания клиенту и контроль недозвона. Гоняется каждые 5 минут.

    Не «суточной задачей на 10:00», а сверкой по каждой записи: первое
    напоминание привязано к часу визита (ровно сутки), второе — к трём часам
    или к вечеру накануне, общего часа у них нет.

    Второе напоминание не уходит тому, кто уже нажал «Подтверждаю»: ответ дан.
    Это единственное отступление от правила «напоминаний два» — в пользу клиента.
    """
    now = now or datetime.now(MSK)
    данные = gh_read_json(BOOKINGS_PATH, default={}) or {}
    первые, вторые, подняли = [], [], []
    отчёт24, отчёт3, передали, отказ = [], [], [], []
    for chat_id, з in данные.items():
        визит = _visit_moment(з)
        if not визит or визит < now or з.get("declined"):
            continue
        есть_сутки = (визит - now) > timedelta(hours=6)
        if not з.get("reminded") and есть_сутки and now >= визит - FIRST_BEFORE:
            api("sendMessage", chat_id=int(chat_id), parse_mode="HTML",
                text=_reminder_text(chat_id, з, 1, визит),
                reply_markup=_reminder_buttons(chat_id, 1, з.get("fmt") == "training"))
            первые.append(chat_id)
            if not з.get("reported24"):
                отчёт_о_подтверждении(chat_id, з, 1)
                отчёт24.append(chat_id)
        elif not з.get("reminded2") and now >= _second_reminder_at(визит):
            if not з.get("confirmed"):
                api("sendMessage", chat_id=int(chat_id), parse_mode="HTML",
                    text=_reminder_text(chat_id, з, 2, визит),
                    reply_markup=_reminder_buttons(chat_id, 2, з.get("fmt") == "training"))
            вторые.append(chat_id)
            if not з.get("reported3"):
                отчёт_о_подтверждении(chat_id, з, 2)
                отчёт3.append(chat_id)
                # Не подтвердил за 3 часа — призыв звонить уже ушёл в группу
                # (см. отчёт_о_подтверждении). Прежняя карточка «недозвон» час
                # спустя говорила бы то же самое второй раз, поэтому отметку
                # ставим здесь и второй раз менеджера не дёргаем.
                if not з.get("confirmed"):
                    подняли.append(chat_id)
        elif (з.get("trainer") and з.get("trainer_assigned")
              and not з.get("trainer_ok") and not з.get("trainer_moved")
              and not з.get("trainer_noanswer_reported")
              and int(з.get("trainer_tries") or 1) < 3
              and _тренер_молчит(з, now)):
            if передать_следующему(chat_id, з,
                                   f"Тренер {з.get('trainer')} не ответил "
                                   f"на карточку гостя за {TRAINER_ANSWER_MIN} минут."):
                передали.append(chat_id)
            else:
                отказ.append(chat_id)
        elif (з.get("reminded2") and not з.get("confirmed") and not з.get("escalated")
              and now >= _escalation_at(_second_reminder_at(визит))):
            _escalate(chat_id, з)
            подняли.append(chat_id)

    if первые or вторые or подняли or отчёт24 or отчёт3 or передали or отказ:
        метка = now.strftime("%Y-%m-%d %H:%M")

        def _отметить(d, а=первые, б=вторые, в=подняли, г=отчёт24, д=отчёт3,
                      е=передали, ж=отказ, м=метка):
            for i in а:
                if i in d:
                    d[i]["reminded"] = м
            for i in б:
                if i in d:
                    d[i]["reminded2"] = м
            for i in в:
                if i in d:
                    d[i]["escalated"] = м
            for i in г:
                if i in d:
                    d[i]["reported24"] = м
            for i in д:
                if i in d:
                    d[i]["reported3"] = м
            # Передали следующему — отметку о молчании снимаем: у нового
            # тренера свой отсчёт (trainer_assigned переставлен).
            for i in е:
                if i in d:
                    d[i]["trainer_noanswer_reported"] = ""
            # Передать некому — помечаем, иначе координатор получит ту же
            # тревогу каждые пять минут до самого визита.
            for i in ж:
                if i in d:
                    d[i]["trainer_noanswer_reported"] = м
        gh_update_json(BOOKINGS_PATH, _отметить,
                       f"тг-бот: напоминания {len(первые)}+{len(вторые)}, "
                       f"недозвон {len(подняли)}, передано {len(передали)}")
    print(f"[визиты] напоминаний: первых {len(первые)}, вторых {len(вторые)}, "
          f"не подтвердили {len(подняли)}, передано тренерам {len(передали)}",
          flush=True)
    return {"первые": первые, "вторые": вторые, "подняли": подняли,
            "передали": передали}


def _когда_словом(iso, now=None):
    """«сегодня», «завтра» или дата — чтобы в ответе клиенту не соврать со днём."""
    if not iso:
        return ""
    now = now or datetime.now(MSK)
    if iso == now.strftime("%Y-%m-%d"):
        return "сегодня"
    if iso == (now + timedelta(days=1)).strftime("%Y-%m-%d"):
        return "завтра"
    return fmt_date_short(iso)


def visit_answer(chat_id, подтвердил, message_id):
    """Клиент нажал «Иду к цели» или «Подберите другое время»."""
