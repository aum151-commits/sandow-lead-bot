    """Провисание: тренер не ответил, клиент не подтвердил, автоподбор не смог.
    Координатору — с причиной; без причины такой отчёт бесполезен."""
    имя = разбор.get("имя") or "без имени"
    телефон = f" · <code>{разбор.get('телефон')}</code>" if разбор.get("телефон") else ""
