# -*- coding: utf-8 -*-
"""Проверка: кто взял заявку в работу и кого зовут за тренером.

Повод — правка Ольги 26.10.2026, дословно: «а для менеджера в любом случае
кнопка — беру в работу, так? иначе как узнаем, кто взял?» и «в спорных
случаях должен вмешиваться координатор тренажёрного зала».

Что было не так. Карточка записи уходила в чат заявок без единой кнопки
«Беру в работу»: заявка из бота приходит в чат именно карточкой записи (по
номеру менеджеров не дёргаем, решение 28.09), поэтому по записям журнал SLA
(taken_at/taken_by) молчал — кто взял клиента, видно не было. А список
свободных тренеров в карточке заканчивался словами «Свободны на … — выберите
тренера» без адресата, и читался как задача менеджеру, хотя тренера назначает
координатор зала.

Проверка держит четыре вещи, которые легко потерять при следующей правке
текста карточки:
 1) «Беру в работу» есть на карточке записи — и когда тренера подобрал бот,
    и когда подбирать будет человек;
 2) список свободных тренеров адресован координатору по нику, а не менеджеру;
 3) в личное сообщение координатору менеджерская кнопка не попадает;
 4) назначение тренера не отбирает у менеджера кнопку «Беру в работу».

Запуск:
    python test_vzyatie_i_koordinator.py
"""
import os
import sys

# Токенов нет и не нужно: все сетевые вызовы подменяются ниже.
os.environ.setdefault("BOT_TOKEN", "test:test")
os.environ.setdefault("GH_TOKEN", "")
os.environ.setdefault("ORDERS_CHAT_ID", "-1001793724014")

import bot  # noqa: E402

провалов = []


def ок(условие, что):
    print(("  ок   " if условие else "  ПРОВАЛ ") + что)
    if not условие:
        провалов.append(что)


вызовы = []          # (метод, аргументы) — всё, что бот попытался отправить


def фейк_api(method, **kw):
    вызовы.append((method, kw))
    return {"ok": True, "result": {"message_id": 7}}


def фейк_заявки(subject_chat_id=None, subject_phone=None, **kw):
    вызовы.append(("send_to_orders", kw))
    return {"ok": True, "result": {"message_id": 7}}


bot.api = фейк_api
bot.send_to_orders = фейк_заявки
bot.gh_read_json = lambda path, default=None: default
bot.gh_update_json = lambda *a, **k: None
bot.remember_booking = lambda *a, **k: None
bot.push_1c_followup = lambda *a, **k: None
bot.подтвердить_автоподбор = lambda *a, **k: None
bot.отчёт_координатору = lambda *a, **k: None
bot.is_live_test = lambda chat_id: False

КООРДИНАТОР = 555111
bot.coordinator_chat_id = lambda: КООРДИНАТОР

КЛИЕНТ = 900900
ТРЕНЕРЫ = bot._TRAINERS[:2]

ЗАПИСЬ = {
    "fmt": "training", "dir": "gym", "phone": "+79991234567", "health": "",
    "time_pref": "27 октября, 18:00", "goal": "keep", "trainer_sex": "any",
    "visit_date": "2026-10-27", "visit_slot": "18:00",
}
ПОЛЬЗОВАТЕЛЬ = {"id": КЛИЕНТ, "first_name": "Иван"}


def подбор_не_смог():
    """Автоподбор не нашёл никого, но свободные на это время есть."""
    bot.авто_тренер = lambda *a, **k: {"тренер": None, "причина": "нет_окон",
                                       "разбор": {}, "годные": [], "альтернативы": []}
    bot._free_trainers_for = lambda date, slot: list(ТРЕНЕРЫ)


def подбор_нашёл(имя):
    bot.авто_тренер = lambda *a, **k: {"тренер": имя, "причина": "",
                                       "разбор": {}, "годные": [], "альтернативы": []}
    bot._free_trainers_for = lambda date, slot: []


def карточка_в_группе():
    for метод, kw in reversed(вызовы):
        if метод == "send_to_orders" and "ЗАПИСЬ" in (kw.get("text") or ""):
            return kw
    return {}


def личное_координатору():
    for метод, kw in reversed(вызовы):
        if метод == "sendMessage" and kw.get("chat_id") == КООРДИНАТОР:
            return kw
    return {}


def кнопки(разметка):
    """Плоский список подписей кнопок из разметки Telegram."""
    подписи = []
    for ряд in ((разметка or {}).get("inline_keyboard") or []):
        for к in ряд:
            подписи.append(к.get("text", ""))
    return подписи


print("1. Автоподбор не смог, свободные тренеры есть — карточку читает координатор")
подбор_не_смог()
вызовы.clear()
bot.finalize_booking(КЛИЕНТ, None, dict(ПОЛЬЗОВАТЕЛЬ), dict(ЗАПИСЬ))
группа = карточка_в_группе()
текст = группа.get("text") or ""
ок(bool(группа), "карточка записи ушла в чат заявок")
# 05.11.2026, правка Ольги: «Салихова — координатор тренажёрного зала! И в чате
# заявок её нет». Поэтому в карточке для отдела продаж её ники и имена не
# называются, а список тренеров кнопками — только у неё в личке (проверяется
# ниже). Здесь держим обратное: в группу это не попадает.
ок(bot.COORDINATOR_TG not in текст,
   "координатор в карточке чата заявок не назван по нику")
ок("координатора зала" in текст,
   "сказано, что выбор тренера — решение координатора зала")
ок("Менеджеру делать ничего не нужно" in текст,
   "менеджеру сказано прямо, что от него тут ничего не требуется")
ок(not any(t in кнопки(группа.get("reply_markup")) for t in ТРЕНЕРЫ),
   "кнопок выбора тренера менеджерам не предлагают — это решение координатора")
ок(any(к == "Беру в работу" for к in кнопки(группа.get("reply_markup"))),
   "на карточке есть кнопка «Беру в работу»")

print("\n2. Кнопка «Беру в работу» несёт id клиента, а не что попало")
данные = [к.get("callback_data") for ряд in
          (группа.get("reply_markup") or {}).get("inline_keyboard", []) for к in ряд]
ок(f"take:{КЛИЕНТ}" in данные,
   f"кнопка помечает заявку клиента ({КЛИЕНТ})")

print("\n3. Личное сообщение координатору — без менеджерской кнопки")
личка = личное_координатору()
ок(bool(личка), "координатору ушло личное сообщение")
ок("Беру в работу" not in кнопки(личка.get("reply_markup")),
   "в личке координатора нет кнопки «Беру в работу»")
ок(all(t in кнопки(личка.get("reply_markup")) for t in ТРЕНЕРЫ),
   "тренеры в личке координатора тоже кнопками")

print("\n4. Тренера подобрал бот — менеджеру всё равно есть что нажать")
подбор_нашёл(ТРЕНЕРЫ[0])
вызовы.clear()
bot.finalize_booking(КЛИЕНТ, None, dict(ПОЛЬЗОВАТЕЛЬ), dict(ЗАПИСЬ))
группа = карточка_в_группе()
ок(ТРЕНЕРЫ[0] in (группа.get("text") or ""),
   "в карточке видно, кого подобрал бот")
ок("Беру в работу" in кнопки(группа.get("reply_markup")),
   "«Беру в работу» осталась — иначе взятие никто не отметит")

print("\n5. Координатор назначил тренера — кнопка взятия не исчезает")
вызовы.clear()
bot.coordinator_confirm(-1001793724014, 7, КЛИЕНТ,
                        {"first_name": "Дарья"}, trainer_name=ТРЕНЕРЫ[0])
разметка = {}
for метод, kw in вызовы:
    if метод == "editMessageReplyMarkup":
        разметка = kw.get("reply_markup") or {}
ок(bool(разметка), "разметку карточки после назначения тренера бот обновил")
ок("Беру в работу" in кнопки(разметка),
   "в новой разметке «Беру в работу» на месте")
ок(f"take:{КЛИЕНТ}" in [к.get("callback_data") for ряд in
                        (разметка.get("inline_keyboard") or []) for к in ряд],
   "кнопка по-прежнему помечает того же клиента")

print("\n6. Первый клик «Беру в работу» пишет, кто взял")
вызовы.clear()
bot.on_button({"id": "cb0", "data": f"take:{КЛИЕНТ}", "from": {"first_name": "Ольга"},
               "message": {"message_id": 7, "chat": {"id": -1001793724014},
                           "text": "📅 ЗАПИСЬ: ТРЕНИРОВКА С ТРЕНЕРОМ"}})
правки = [kw for метод, kw in вызовы if метод == "editMessageText"]
ок(bool(правки), "карточка обновилась")
ок(bool(правки) and "✅ В работе: Ольга" in (правки[-1].get("text") or ""),
   "в карточке появилось имя того, кто взял")

print("\n7. Повторный клик не плодит строки «В работе»")
вызовы.clear()
bot.on_button({"id": "cb1", "data": f"take:{КЛИЕНТ}", "from": {"first_name": "Ольга"},
               "message": {"message_id": 7, "chat": {"id": -1001793724014},
                           "text": "📅 ЗАПИСЬ\n\n✅ В работе: Елизавета"}})
правки = [kw for метод, kw in вызовы if метод == "editMessageText"]
ок(not правки, "второй клик карточку не переписывает")
подсказка = [kw for метод, kw in вызовы if метод == "answerCallbackQuery"]
ок(bool(подсказка) and "Елизавета" in (подсказка[-1].get("text") or ""),
   "вместо перезаписи бот подсказывает, у кого заявка")

print("\n8. Заявка с сайта тоже с кнопкой взятия")
ок("кнопки_карточки(user[\"id\"])" in open("bot.py", encoding="utf-8").read(),
   "карточка с сайта собирает кнопки через кнопки_карточки")

# ── Кому можно выбирать тренера ───────────────────────────────────────────────
# Правка Ольги 26.10.2026: тренера назначает координатор зала; менеджер видит
# имена кнопками, но назначить не может.
выбрали = []
bot.coordinator_confirm = lambda *a, **k: выбрали.append((a, k))


def нажатие_тренера(кто):
    вызовы.clear()
    выбрали.clear()
    bot.on_button({"id": "cb-t", "data": f"at:{КЛИЕНТ}:0", "from": кто,
                   "message": {"message_id": 7, "chat": {"id": -1001793724014},
                               "text": "📅 ЗАПИСЬ: ТРЕНИРОВКА С ТРЕНЕРОМ"}})
    подсказки = [kw.get("text") or "" for метод, kw in вызовы
                 if метод == "answerCallbackQuery"]
    return bool(выбрали), (подсказки[-1] if подсказки else "")


print("\n9. Менеджер нажимает имя тренера — назначения не происходит")
назначил, подсказка = нажатие_тренера({"id": 777001, "first_name": "Елизавета",
                                       "username": "elizaveta_op"})
ок(not назначил, "тренер менеджером не назначен")
ок("координатор зала" in подсказка, "менеджеру объяснили, чьё это решение")

print("\n10. Координатор нажимает имя тренера — назначение идёт")
назначил, _ = нажатие_тренера({"id": КООРДИНАТОР, "first_name": "Дарья",
                               "username": "salikhovadaria"})
ок(назначил, "по chat_id координатора назначение проходит")
назначил, _ = нажатие_тренера({"id": 777002, "first_name": "Дарья",
                               "username": bot.COORDINATOR_TG.lstrip("@")})
ок(назначил, "по нику координатора тоже проходит, если chat_id ещё неизвестен")

print("\n11. Ольга тренера не назначает — это работа координатора")
назначил, подсказка = нажатие_тренера({"id": int(bot.FALLBACK_CHAT),
                                       "first_name": "Ольга"})
ок(not назначил, "у владельца клуба кнопка тоже заперта")

