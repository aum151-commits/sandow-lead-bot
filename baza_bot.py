def обработать_сообщение(сообщение):
    чат = сообщение["chat"]["id"]
    кто = сообщение.get("from", {})
    имя_в_телеграме = кто.get("first_name") or "друг"
    ник = ("@" + кто["username"]) if кто.get("username") else \
        " ".join(ч for ч in [кто.get("first_name"), кто.get("last_name")] if ч)

    if сообщение["chat"]["type"] in ("group", "supergroup"):
        запомнить_группу(чат, сообщение["chat"].get("title", ""))
        ждём = ЖДЁМ_ПРИЧИНУ.get(str(чат))
        ответ_на_бота = (сообщение.get("reply_to_message") or {}).get("from", {}).get("is_bot")
        if ждём and ждём.get("своими_словами") and ответ_на_бота:
            причина = (сообщение.get("text") or "").strip()[:300] or "(без текста)"
            записать_отказ(ждём["номер"], "другое: " + причина, ждём.get("кто", ""))
            ЖДЁМ_ПРИЧИНУ.pop(str(чат), None)
            отправить(чат, "Записал: {} — не наш, причина — {}.".format(ждём["номер"], причина))
        return

    состояние = СОСТОЯНИЯ.взять(чат)
    текст = (сообщение.get("text") or "").strip()

    if сообщение.get("contact"):
        телефон = разобрать_телефон(сообщение["contact"].get("phone_number", ""))
        if телефон and состояние.get("имя"):
            шаг_занятость(чат, состояние["имя"], телефон)
        else:
            отправить(чат, ВОПРОС_ТЕЛЕФОН_ИНАЧЕ)
        return

    if текст.startswith("/start") or текст in ("/help", "/?"):
        метка = текст[6:].strip().lower() if текст.startswith("/start") else ""
        СОСТОЯНИЯ.очистить(чат)
        шаг_приветствие(чат, метка, ник, имя_в_телеграме)
        return

    шаг = состояние.get("шаг", "нет")

    if шаг in ("ждём_имя", "ждём_имя_подтверждения"):
        имя = текст[:60]
        if len(имя) < 2 or имя.lower().rstrip("!.") in ПРИВЕТСТВИЯ:
            отправить(чат, ВОПРОС_ИМЯ_СНОВА)
            return
        СОСТОЯНИЯ.поправить(чат, кто=ник)
        шаг_телефон(чат, имя)
        return

    if шаг == "ждём_телефон":
        if текст.lower().startswith("введу вручную"):
            отправить(чат, ВОПРОС_ТЕЛЕФОН_ИНАЧЕ)
            return
        if текст.lower().startswith("отправить мой номер"):
            отправить(чат, "Нажми, пожалуйста, кнопку «Отправить мой номер» внизу "
                           "экрана — она подставит номер сама. Или напиши номер "
                           "сообщением.")
            return
        телефон = разобрать_телефон(текст)
        if not телефон:
            отправить(чат, "Не разобрал номер. Напиши цифрами, например "
                           "+7 999 123-45-67, или нажми «Отправить мой номер».")
            return
        шаг_занятость(чат, состояние.get("имя") or имя_в_телеграме, телефон)
        return

    if шаг == "ждём_занятость_своими":
        занятость = текст[:200]
        if len(занятость) < 3:
            отправить(чат, ВОПРОС_ЗАНЯТОСТЬ_СВОИМИ)
            return
        СОСТОЯНИЯ.поправить(чат, занятость=занятость)
        шаг_клиенты(чат)
        return

    if шаг == "ждём_занятость":
        отправить(чат, НЕПОНЯТНО, кнопки_занятость())
        return

    if шаг == "ждём_клиентов":
        отправить(чат, НЕПОНЯТНО, кнопки_клиенты())
        return

    if шаг == "нет":
        # Первое сообщение без «Старта» — начинаем знакомство, а не молчим.
        шаг_приветствие(чат, "", ник, имя_в_телеграме)
        return

    отправить(чат, НЕПОНЯТНО)


def обработать_нажатие(нажатие):
    чат = нажатие["message"]["chat"]["id"]
    сообщение = нажатие["message"]["message_id"]
    данные = нажатие.get("data", "")
    кто = нажатие.get("from", {})
    ник = ("@" + кто["username"]) if кто.get("username") else \
        " ".join(ч for ч in [кто.get("first_name"), кто.get("last_name")] if ч)
    имя_в_телеграме = кто.get("first_name") or "друг"
    состояние = СОСТОЯНИЯ.взять(чат)

    звать("answerCallbackQuery", callback_query_id=нажатие["id"])

    if данные == "name:ok":
        шаг_телефон(чат, имя_в_телеграме)
        return

    if данные == "name:edit":
        СОСТОЯНИЯ.поправить(чат, шаг="ждём_имя")
        отправить(чат, ВОПРОС_ИМЯ_ИНАЧЕ)
        return

    if данные.startswith("job:"):
        if состояние.get("шаг") != "ждём_занятость":
            return  # двойное нажатие или старые кнопки — вторую заявку не плодим
        код = данные.split(":", 1)[1]
        if код == "other":
            СОСТОЯНИЯ.поправить(чат, шаг="ждём_занятость_своими")
            отправить(чат, ВОПРОС_ЗАНЯТОСТЬ_СВОИМИ)
            return
        СОСТОЯНИЯ.поправить(чат, занятость=ЗАНЯТОСТЬ.get(код, код))
        шаг_клиенты(чат)
        return

    if данные.startswith("cl:"):
        if состояние.get("шаг") != "ждём_клиентов":
            return  # двойное нажатие не должно давать вторую заявку
        код = данные.split(":", 1)[1]
        СОСТОЯНИЯ.поправить(чат, клиентов=КЛИЕНТЫ.get(код, код))
        шаг_спасибо(чат, кто=ник)
        return

    if данные.startswith("take:"):
        номер = данные.split(":", 1)[1]
        изменить(чат, сообщение, "{} в работе у {}".format(номер, ник))
        return

    if данные.startswith("reject:"):
        номер = данные.split(":", 1)[1]
        ЖДЁМ_ПРИЧИНУ[str(чат)] = {"номер": номер, "кто": ник}
        отправить(чат, "Почему не наш — {}? Нажми причину, она уйдёт в отчёт.".
                  format(номер), кнопки_причин(номер))
        return

    if данные.startswith("why:"):
        _, номер, код = данные.split(":", 2)
        причина = ПРИЧИНЫ.get(код, код)
        if код == "dr":
            ЖДЁМ_ПРИЧИНУ[str(чат)] = {"номер": номер, "кто": ник, "своими_словами": True}
            отправить(чат, "Напиши причину ответом на это сообщение — запишу как есть.")
            return
        записать_отказ(номер, причина, ник)
        изменить(чат, сообщение, "{} — не наш. Причина: {}.".format(номер, причина))
        return

    # Кнопка из прошлых редакций бота (в чатах они ещё висят) — не молчим.
    подсказка = {
        "ждём_имя_подтверждения": кнопки_имя(имя_в_телеграме),
        "ждём_занятость": кнопки_занятость(),
        "ждём_клиентов": кнопки_клиенты(),
    }.get(состояние.get("шаг"))
    if подсказка:
        отправить(чат, НЕПОНЯТНО, подсказка)
    else:
        шаг_приветствие(чат, "", ник, имя_в_телеграме)


def обработать_обновление(обновление):
    try:
        if "message" in обновление:
            обработать_сообщение(обновление["message"])
        elif "callback_query" in обновление:
            обработать_нажатие(обновление["callback_query"])
        elif "my_chat_member" in обновление:
            член = обновление["my_chat_member"]
            чат = член["chat"]
            статус = член["new_chat_member"]["status"]
            if чат.get("type") in ("group", "supergroup"):
                запомнить_группу(чат["id"], чат.get("title", ""))
                if OLGA_ID and статус == "member":
                    отправить(OLGA_ID, "Бот добавлен в группу «{}» (id {}).".
                              format(чат.get("title"), чат["id"]))
    except Exception:
        print("[ошибка] обновление не обработано:")
        traceback.print_exc()


