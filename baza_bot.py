def прочитать_env(путь=ПАПКА / ".env"):
    значения = {}
    if not путь.exists():
        return значения
    for строка in путь.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#") or "=" not in строка:
            continue
        ключ, значение = строка.split("=", 1)
        значения[ключ.strip()] = значение.strip()
    return значения


