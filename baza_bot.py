def запустить():
    if not TOKEN:
        print("Нет ключа бота в .env — нечего запускать.")
        sys.exit(1)
    me = звать("getMe")
    if not me:
        print("Телеграм не ответил на проверку ключа.")
        sys.exit(1)

    # Страховка: бот уже работает на сервере и получает сообщения толчком.
    # Если запустить опрос здесь, Телеграм начнёт отдавать сообщения нам, и
    # живой бот замолчит — человек напишет тренеру и не получит ответа.
    инфо = звать("getWebhookInfo") or {}
    if инфо.get("url") and os.environ.get("BAZA_POLL_FORCE", "") != "1":
        print("ОСТАНОВЛЕН: бот уже работает на сервере ({}).".format(инфо["url"]))
        print("Опрос здесь отключит живого бота. Тексты проверять — у бота в Телеграме.")
        print("Нужен именно локальный опрос — запустите с BAZA_POLL_FORCE=1.")
        sys.exit(2)

    print("Бот @{} на связи. {}".format(
        me["username"], json.dumps(состояние_бота(), ensure_ascii=False)))

    смещение = 0
    while True:
        try:
            обновления = звать("getUpdates", offset=смещение, timeout=25,
                               allowed_updates=["message", "callback_query", "my_chat_member"])
            if обновления is None:
                time.sleep(3)
                continue
            for обновление in обновления:
                смещение = обновление["update_id"] + 1
                начало = time.time()
                обработать_обновление(обновление)
                долго = time.time() - начало
                if долго > 1:
                    print("[скорость] ответ на {} занял {:.1f} с".format(
                        "сообщение" if "message" in обновление else "нажатие", долго))
        except KeyboardInterrupt:
            print("Остановлен вручную.")
            return
        except Exception:
            print("[цикл] сбой, продолжаю:")
            traceback.print_exc()
            time.sleep(3)


