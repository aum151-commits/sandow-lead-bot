def разобрать_телефон(текст):
    цифры = re.sub(r"\D", "", текст or "")
    if len(цифры) == 11 and цифры[0] in "78":
        return "+7" + цифры[1:]
    if len(цифры) == 10 and цифры[0] == "9":
        return "+7" + цифры
    return None


def красиво(телефон):
    if not телефон or len(телефон) != 12:
        return телефон or "—"
    return "{} {} {}-{}-{}".format(телефон[0:2], телефон[2:5], телефон[5:8],
                                   телефон[8:10], телефон[10:12])


