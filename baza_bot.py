def прочитать_json(путь, по_умолчанию):
    try:
        return json.loads(путь.read_text(encoding="utf-8"))
    except Exception:
        return по_умолчанию


def записать_json(путь, данные):
    try:
        путь.write_text(json.dumps(данные, ensure_ascii=False, indent=1), encoding="utf-8")
    except Exception as ошибка:
        print("[файл {}] не записался: {}".format(путь.name, ошибка))


class Состояния:
    """Память диалогов: кто на каком шаге."""

    def __init__(self, путь=СОСТОЯНИЯ_ФАЙЛ):
        self.путь = путь
        self.данные = прочитать_json(путь, {})

    def взять(self, чат):
        return dict(self.данные.get(str(чат), {"шаг": "нет"}))

    def поставить(self, чат, состояние):
        self.данные[str(чат)] = dict(состояние)
        self.сохранить()

    def поправить(self, чат, **поля):
        состояние = self.взять(чат)
        состояние.update(поля)
        self.поставить(чат, состояние)
        return состояние

    def очистить(self, чат):
        self.данные.pop(str(чат), None)
        self.сохранить()

    def сохранить(self):
        записать_json(self.путь, self.данные)


