def отправить(чат, текст, клавиатура=None):
    параметры = {"chat_id": чат, "text": текст, "disable_web_page_preview": True}
    if клавиатура:
        параметры["reply_markup"] = клавиатура
    return звать("sendMessage", **параметры)


def изменить(чат, сообщение, текст, клавиатура=None):
    параметры = {"chat_id": чат, "message_id": сообщение, "text": текст,
                 "disable_web_page_preview": True,
                 "reply_markup": клавиатура or {"inline_keyboard": []}}
    return звать("editMessageText", **параметры)


def это_проверка(чат):
    """§0г: живой прогон Ольги или включённый режим проверки."""
    return TEST_MODE or (OLGA_ID and str(чат) == str(OLGA_ID))


def следующий_номер():
    номер = 1
    if ЗАЯВКИ_ФАЙЛ.exists():
        with ЗАЯВКИ_ФАЙЛ.open(encoding="utf-8") as файл:
            номер += sum(1 for _ in файл)
    return "БС-{:04d}".format(номер)


def карточка(заявка, пометка=""):
    строки = []
    if пометка:
        строки += [пометка, ""]
    строки += [
        "БАЗА САНДОВ — заявка тренера",
        "Номер: {}".format(заявка["номер"]),
        "Имя: {}".format(заявка.get("имя") or "—"),
        "Телефон: {}".format(красиво(заявка.get("телефон"))),
        "Как работает сейчас: {}".format(заявка.get("занятость") or "не сказал"),
        "Клиентов: {}".format(заявка.get("клиентов") or "не сказал"),
        "Телеграм: {}".format(заявка.get("кто") or "—"),
        "Откуда: {}".format(заявка.get("откуда") or "прямая ссылка"),
        "Время: {}".format(заявка.get("время") or datetime.now().strftime("%d.%m %H:%M")),
    ]
    return "\n".join(строки)


def отправить_карточку(заявка):
    """Карточка уходит в группу заявок. Проверка — только Ольге в личку (§0г)."""
    проверка = это_проверка(заявка["чат"])
    пометка = "ПРОВЕРКА — в группу не ушло, в счёт не считать" if проверка else ""
    текст = карточка(заявка, пометка)
    клавиатура = кнопки_карточки(заявка["номер"], заявка.get("кто", ""),
                                 заявка.get("телефон", ""))
    if проверка:
        отправить(OLGA_ID, текст, клавиатура)
        return "ольге"
    if GROUP_ID:
        отправить(GROUP_ID, текст, клавиатура)
        return "группа"
    отправить(OLGA_ID, "Группа заявок не подключена — заявка пришла сюда\n\n" + текст,
              клавиатура)
    return "ольге"


