def звать(метод, **параметры):
    начало = time.time()
    try:
        r = requests.post(API.format(метод), json=параметры, timeout=30)
        данные = r.json()
        if not данные.get("ok"):
            print("[телеграм] {} -> {}".format(метод, данные.get("description")))
            return None
        return данные.get("result")
    except Exception as ошибка:
        print("[телеграм] {} не прошёл: {}".format(метод, ошибка))
        return None
    finally:
        долго = time.time() - начало
        if долго > 1.5:
            print("[скорость] {} занял {:.1f} с".format(метод, долго))


