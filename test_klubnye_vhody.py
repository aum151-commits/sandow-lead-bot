# -*- coding: utf-8 -*-
"""Проверка клубных входов без обращения к Телеграму и GitHub.

Зачем. bot.py — боевой: он принимает заявки с сайта, и ошибка в нём
видна не в логе, а в потерянном клиенте. Правку под печатные макеты
(коды razdevalka/turniket) нужно проверить до выкладки, поэтому здесь
подменяются api() и save_subscriber(), а сценарий прогоняется вхолостую.

Что проверяем:
  1. код с макета ведёт СРАЗУ в меню члена клуба, без развилки
     «Хочу в клуб / Уже занимаюсь»;
  2. источник уходит в базу подписчиков (раньше терялся при перезапуске);
  3. прежнее поведение лендингов и голого /start не сломано.

Запуск:
    python test_klubnye_vhody.py
"""
import os
import sys

# Токенов нет и не нужно: сетевые вызовы подменяются ниже.
os.environ.setdefault("BOT_TOKEN", "test:test")
os.environ.setdefault("GH_TOKEN", "")

import bot  # noqa: E402

отправленные = []
сохранённые = []


def фейк_api(method, **kw):
    отправленные.append((method, kw))
    return {"ok": True, "result": {"message_id": 1}}


def фейк_save(user, segment=None, phone=None, call_name=None, source=None):
    сохранённые.append({"segment": segment, "source": source})


bot.api = фейк_api
bot.save_subscriber = фейк_save
bot.archive_dialog = lambda *a, **k: None


def прогнать(текст):
    отправленные.clear()
    сохранённые.clear()
    bot.on_message({
        "chat": {"id": 777, "type": "private"},
        "from": {"id": 777, "first_name": "Тест"},
        "text": текст,
        "message_id": 1,
    })
    весь = " | ".join(str(kw.get("text", "")) for _, kw in отправленные)
    кнопки = " | ".join(str(kw.get("reply_markup", "")) for _, kw in отправленные)
    return весь, кнопки


провалов = 0


def проверить(условие, описание):
    global провалов
    print(('  ОК   ' if условие else '  СБОЙ ') + описание)
    if not условие:
        провалов += 1


print('1. Код с макета в раздевалке')
текст, кнопки = прогнать('/start razdevalka')
проверить('Хочу в клуб' not in кнопки, 'развилки «Хочу в клуб» нет')
проверить('Расписание' in кнопки, 'сразу показано меню члена клуба')
проверить('Телеграм клуба' in текст, 'приветствие про Телеграм клуба')
проверить(any(з['source'] == 'макет в раздевалке' for з in сохранённые),
          'источник «макет в раздевалке» ушёл в базу')
проверить(any(з['segment'] == 'member' for з in сохранённые),
          'человек помечен как член клуба')

print('2. Код у турникета')
текст, кнопки = прогнать('/start turniket')
проверить(any(з['source'] == 'макет у турникета' for з in сохранённые),
          'источник «макет у турникета» ушёл в базу')

print('3. Прежнее поведение лендинга не сломано')
текст, кнопки = прогнать('/start boks')
проверить('Хочу в клуб' in кнопки, 'развилка на месте')
проверить('бокс' in текст.lower(), 'текст лендинга про бокс')
проверить(any(з['source'] == 'лендинг Бокс' for з in сохранённые),
          'источник лендинга тоже пишется')

print('4. Голый /start не сломан')
текст, кнопки = прогнать('/start')
проверить('Хочу в клуб' in кнопки, 'развилка на месте')
проверить('Сандов Фитнес' in текст, 'обычное приветствие')

print('5. Мусор в коде не ломает бота')
текст, кнопки = прогнать('/start <b>злой</b>')
проверить('Хочу в клуб' in кнопки, 'откат к обычному приветствию')

print()
print('ПРОВАЛОВ:', провалов)
sys.exit(1 if провалов else 0)
