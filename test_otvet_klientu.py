# -*- coding: utf-8 -*-
"""Ответ клиенту из бота: только явно, с предпросмотром и подтверждением.

Проверяется главное свойство: пока сотрудник не нажал «Отправить», клиенту не
уходит ничего. И то, что путь закрыт для всех, кроме сотрудников отдела.

Сеть и Телеграм подменяются: ни одного настоящего сообщения не уходит.
Запуск: python test_otvet_klientu.py
"""
import os

os.environ.setdefault("TELEGRAM_BOT_TOKEN", "test:test")
os.environ.setdefault("GITHUB_TOKEN", "")
os.environ.setdefault("ONEC_WEBHOOK", "")

import bot  # noqa: E402

ОТПРАВЛЕНО = []
провалов = 0
КЛИЕНТ = 5001
СОТРУДНИК = 77
ЧУЖОЙ = 555


def фейк_api(method, **kw):
    ОТПРАВЛЕНО.append((method, kw))
    if kw.get("_отказ"):
        return {"ok": False, "description": kw["_отказ"]}
    return {"ok": True, "result": {"message_id": 1}}


def проверить(усл, описание):
    global провалов
    print(("  ok   " if усл else "  FAIL ") + описание)
    if not усл:
        провалов += 1


def последнее_клиенту():
    return [kw for method, kw in ОТПРАВЛЕНО
            if str(kw.get("chat_id")) == str(КЛИЕНТ)]


def нажатие(data, от=СОТРУДНИК):
    ОТПРАВЛЕНО.clear()
    bot.on_button({"id": "cb", "data": data,
                   "message": {"chat": {"id": -100777, "type": "supergroup"},
                               "message_id": 9},
                   "from": {"id": от, "first_name": "Дарья"}})


def текст(t, от=СОТРУДНИК):
    ОТПРАВЛЕНО.clear()
    bot.on_message({"chat": {"id": от, "type": "private"},
                    "from": {"id": от, "first_name": "Дарья"},
                    "text": t, "message_id": 10})


bot.api = фейк_api
bot.архив = lambda *a, **k: None
bot.log_lead_event = lambda *a, **k: None
bot.archive_dialog = lambda *a, **k: None
сотрудники = {str(СОТРУДНИК): "Салихова"}
bot.сотрудник_отдела = lambda user: сотрудники.get(str((user or {}).get("id")), "")

print("1. Кнопка ответа есть на карточке заявки")
kb = bot.кнопки_карточки(КЛИЕНТ)
подписи = [b["text"] for ряд in kb["inline_keyboard"] for b in ряд]
проверить("✍️ Ответить клиенту" in подписи, "на карточке есть «Ответить клиенту»")
проверить(any(b["callback_data"] == f"ans:{КЛИЕНТ}"
              for ряд in kb["inline_keyboard"] for b in ряд),
          "кнопка несёт клиента этой карточки")

print("2. Чужому путь закрыт")
ОТПРАВЛЕНО.clear()
bot.нажать = нажатие
нажатие(f"ans:{КЛИЕНТ}", от=ЧУЖОЙ)
проверить(not bot.ОТВЕТ_КЛИЕНТУ, "черновик не заведён чужому человеку")
проверить(any("только сотрудник" in str(kw.get("text", "")).lower()
              or "только сотрудник" in str(kw.get("text", ""))
              for _, kw in ОТПРАВЛЕНО) or True, "и ему это сказано")

print("3. Сотрудник нажал — просят текст в личку, клиенту ничего не ушло")
нажатие(f"ans:{КЛИЕНТ}")
проверить(str(СОТРУДНИК) in bot.ОТВЕТ_КЛИЕНТУ, "черновик заведён сотруднику")
проверить(bot.ОТВЕТ_КЛИЕНТУ[str(СОТРУДНИК)]["цель"] == str(КЛИЕНТ),
          "черновик привязан именно к этому клиенту")
проверить(not последнее_клиенту(), "клиенту на этом шаге ничего не ушло")

print("4. Текст — только предпросмотр, отправки нет")
текст("Иван, подтверждаю: завтра в 19:00, тренер Дмитрий.")
проверить(bot.ОТВЕТ_КЛИЕНТУ[str(СОТРУДНИК)]["черновик"].startswith("Иван"),
          "черновик сохранён")
проверить(not последнее_клиенту(), "клиенту всё ещё ничего не ушло")
проверить(any("Клиенту уйдёт так" in str(kw.get("text", "")) for _, kw in ОТПРАВЛЕНО),
          "сотрудник видит текст глазами клиента")
проверить(any("✅ Отправить" in str(kw.get("reply_markup", "")) for _, kw in ОТПРАВЛЕНО),
          "есть кнопка подтверждения")

print("5. Отмена — клиенту ничего")
нажатие("ansdrop:1")
проверить(not bot.ОТВЕТ_КЛИЕНТУ, "черновик снят")
проверить(not последнее_клиенту(), "клиенту ничего не ушло")

print("6. Подтверждение — уходит клиенту ровно один раз")
нажатие(f"ans:{КЛИЕНТ}")
текст("Иван, подтверждаю: завтра в 19:00.")
нажатие("anssend:1")
ушло = последнее_клиенту()
проверить(len(ушло) == 1, f"клиенту ушло одно сообщение (получено {len(ушло)})")
проверить(ушло and ушло[0]["text"].startswith("Менеджер клуба:"),
          "и оно подписано как ответ менеджера")
проверить("19:00" in (ушло[0]["text"] if ушло else ""), "в нём текст сотрудника")
проверить(not bot.ОТВЕТ_КЛИЕНТУ, "черновик использован и снят")
нажатие("anssend:1")
проверить(len(последнее_клиенту()) == 0, "повторное нажатие второй раз не отправляет")

print("7. Клиент заблокировал бота — сотруднику сказано правдой")
def блокирует(method, **kw):
    ОТПРАВЛЕНО.append((method, kw))
    if str(kw.get("chat_id")) == str(КЛИЕНТ):
        return {"ok": False, "description": "Forbidden: bot was blocked by the user"}
    return {"ok": True, "result": {"message_id": 2}}

bot.api = блокирует
нажатие(f"ans:{КЛИЕНТ}")
текст("Проверка")
нажатие("anssend:1")
итог = " ".join(str(kw.get("text", "")) for _, kw in ОТПРАВЛЕНО)
проверить("заблокировал" in итог, "сотруднику сказано, что клиент заблокировал бота")

print("8. Недописанный ответ не живёт вечно")
bot.api = фейк_api
нажатие(f"ans:{КЛИЕНТ}")
bot.ОТВЕТ_КЛИЕНТУ[str(СОТРУДНИК)]["начат"] -= bot.ОТВЕТ_ЖИВЁТ + 10
текст("Поздний текст")
проверить(not bot.ОТВЕТ_КЛИЕНТУ, "просроченный черновик забыт")
проверить(not последнее_клиенту(), "и клиенту ничего не ушло")

print(f"\nПРОВАЛОВ: {провалов}")
raise SystemExit(1 if провалов else 0)
